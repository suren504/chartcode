p_v2 <- ggplot(df_full, aes(x = 百回合得分, y = 百回合失分)) +
  
  # 【十字基准线】
  geom_vline(xintercept = 111.3, linetype = "dashed", color = "#CCCCCC") +
  geom_hline(yintercept = 111.3, linetype = "dashed", color = "#CCCCCC") +
  
  # 【关键点：气泡图逻辑】
  # size = 节奏：球打得越快，圆圈越大
  # fill = 修正净胜分：颜色代表硬实力
  geom_point(aes(size = 节奏, fill = 修正净胜分), shape = 21, color = "white", alpha = 0.8) +
  
  # 【智能标签】
  geom_text_repel(
    aes(label = 标签),
    size = 3.5, family = "Microsoft YaHei", fontface = "bold",
    lineheight = 0.9, box.padding = 0.5
  ) +
  
  # 【轴与配色】
  scale_y_reverse() + # 依然反转轴
  scale_size_continuous(range = c(3, 12), name = "比赛节奏") + # 控制气泡大小范围
  scale_fill_gradient2(low = "#D9534F", mid = "#E8ECEF", high = "#006992", midpoint = 0) +
  
  # 【样式】
  theme_minimal(base_family = "Microsoft YaHei") +
  theme(
    legend.position = "right",
    plot.title = element_text(size = 20, face = "bold"),
    axis.title = element_text(face = "bold")
  ) +
  labs(
    title = "欧洲杯全维度战力矩阵",
    subtitle = "圆圈大小代表[节奏]，位置代表[效率]，文字标注[战绩]",
    x = "进攻效率 (百回合得分)",
    y = "防守效率 (百回合失分, 向上为优)"
  )

